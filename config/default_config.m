function cfg = default_config()
%DEFAULT_CONFIG Return every VibraSmash processing setting in one struct.
%
%   cfg = default_config()
%
%   Each setting is defined once, in the table below, with its provenance:
%
%     proposal     value stated in VibraSmash_Proposal.docx; changing it
%                  changes the study, so tests pin these values.
%     provisional  engineering choice made for this software where the
%                  proposal gives no value; may be revised during pilot
%                  testing, but must be logged in docs/settings_log.md and
%                  frozen before evaluation data is processed.
%     pilot        must be measured from pilot recordings; empty ([])
%                  until then, and code that needs it must refuse to run.
%
%   The full table is kept in cfg.provenance (columns: path, value,
%   source, note) so it can be printed into reports and run logs.
%
%   Tests: tests/unit/test_default_config.m

S = settings_table();
cfg = struct();
for i = 1:size(S, 1)
    parts = strsplit(S{i,1}, '.');
    cfg = setfield(cfg, parts{:}, S{i,2}); %#ok<SFLD>
end
cfg.provenance = S;
cfg.config_version = 'stage8-2026-10-21';
end

